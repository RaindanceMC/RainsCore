def rows(art):
    return [line for line in art.strip("\n").split("\n")]


def glyphs():
    """Every drawn character, as (character, rows of art, first row in the cell)."""
    out = []
    for ch, art in CAPS.items():
        out.append((ch, rows(art), CAP_TOP))
    for ch, art in SMALL.items():
        out.append((ch, rows(art), CAP_TOP + 2))
    for ch, art in DIGITS.items():
        out.append((ch, rows(art), CAP_TOP + 1))
    for ch, (art, top) in MARKS.items():
        out.append((ch, rows(art), top))
    # umlauts: the letter with two dots above it
    for base, umlaut in (("A", "Ä"), ("O", "Ö"), ("U", "Ü"),
                         ("a", "ä"), ("o", "ö"), ("u", "ü")):
        art = rows(CAPS[base] if base.isupper() else SMALL[base])
        width = len(art[0])
        line = ["."] * width
        line[(width - 1) // 2 - 1] = "#"
        line[width // 2 + 1] = "#"
        top = CAP_TOP if base.isupper() else CAP_TOP + 2
        out.append((umlaut, ["".join(line), "." * width] + art, top - 2))
    # ß: a small-capital double s, as German small caps set it
    s = rows(SMALL["s"])
    out.append(("ß", [a + "." + a for a in s], CAP_TOP + 2))
    return out


def sheet():
    """The glyph grid (16 per row) and the chars lists the font provider wants, row by row."""
    drawn = glyphs()
    per_row = 16
    lines = (len(drawn) + per_row - 1) // per_row
    img = Image.new("RGBA", (per_row * CELL_W * 2, lines * CELL_H), (0, 0, 0, 0))
    chars = []
    px = img.load()
    for i, (ch, art, top) in enumerate(drawn):
        col, row = i % per_row, i // per_row
        if col == 0:
            chars.append("")
        chars[-1] += ch
        for y, line in enumerate(art):
            for x, c in enumerate(line):
                if c == "#":
                    px[col * CELL_W * 2 + x, row * CELL_H + top + y] = (255, 255, 255, 255)
    # pad the last row so every row has the same number of cells
    chars[-1] += "\u0000" * (per_row - len(chars[-1]))
    return img, chars


def provider(namespace):
    img, chars = sheet()
    return img, {"type": "bitmap", "file": f"{namespace}:font/title.png", "ascent": ASCENT, "height": CELL_H,
                 "chars": chars}
