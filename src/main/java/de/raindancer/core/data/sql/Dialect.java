package de.raindancer.core.data.sql;

import java.util.Locale;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * The SQL a database speaks.
 *
 * <p>Every schema in the field was written for SQLite, and a server upgrading from 1.x has its tables
 * built from exactly those steps. So the steps stay SQLite and Postgres gets them translated, rather
 * than every plugin keeping two copies of its schema that drift apart. Only DDL is translated: the
 * types and the clauses SQLite has and Postgres lacks. Queries are expected to be portable already
 * ({@code ON CONFLICT … excluded}, {@code RETURNING} and {@code LIMIT/OFFSET} mean the same in both).
 */
public enum Dialect {

    SQLITE,
    POSTGRESQL;

    private static final Pattern DDL = Pattern.compile("^\\s*(CREATE|ALTER)\\b", Pattern.CASE_INSENSITIVE);

    private static final Pattern ROWID_KEY = Pattern.compile(
            "\\bINTEGER\\s+PRIMARY\\s+KEY(\\s+AUTOINCREMENT)?\\b", Pattern.CASE_INSENSITIVE);
    private static final Pattern COLLATE_NOCASE = Pattern.compile("\\s+COLLATE\\s+NOCASE\\b", Pattern.CASE_INSENSITIVE);
    private static final Pattern WITHOUT_ROWID = Pattern.compile("\\s+WITHOUT\\s+ROWID\\b", Pattern.CASE_INSENSITIVE);
    private static final Pattern AUTOINCREMENT = Pattern.compile("\\s+AUTOINCREMENT\\b", Pattern.CASE_INSENSITIVE);
    private static final Pattern INTEGER = Pattern.compile("\\b(INTEGER|INT)\\b", Pattern.CASE_INSENSITIVE);
    private static final Pattern FLOATING = Pattern.compile("\\b(REAL|DOUBLE|FLOAT)\\b(?!\\s+PRECISION)", Pattern.CASE_INSENSITIVE);
    private static final Pattern BLOB = Pattern.compile("\\bBLOB\\b", Pattern.CASE_INSENSITIVE);

    private static final String IDENTITY = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";

    /** One step of a schema, in this dialect. */
    public String translate(String sql) {
        if (this == SQLITE || sql == null || sql.isBlank()) {
            return sql;
        }
        StringBuilder out = new StringBuilder(sql.length() + 32);
        for (String statement : splitStatements(sql)) {
            out.append(DDL.matcher(statement).find() ? translateDdl(statement) : statement);
        }
        return out.toString();
    }

    /** The operator for a LIKE that does not care about case. SQLite's LIKE already ignores ASCII case. */
    public String likeIgnoringCase() {
        return this == POSTGRESQL ? "ILIKE" : "LIKE";
    }

    public static Dialect named(String name) {
        if (name == null) {
            return SQLITE;
        }
        return switch (name.trim().toLowerCase(Locale.ROOT)) {
            case "postgresql", "postgres", "pg" -> POSTGRESQL;
            default -> SQLITE;
        };
    }

    // ---------------------------------------------------------------------------- translation

    /** Rewrites one DDL statement, outside of quoted text only. */
    private static String translateDdl(String statement) {
        StringBuilder out = new StringBuilder(statement.length() + 32);
        int at = 0;
        while (at < statement.length()) {
            int quote = nextQuote(statement, at);
            out.append(rewrite(statement.substring(at, quote)));
            if (quote >= statement.length()) {
                break;
            }
            int end = closingQuote(statement, quote);
            out.append(statement, quote, end);
            at = end;
        }
        return out.toString();
    }

    private static String rewrite(String plain) {
        String result = replaceAll(ROWID_KEY, plain, "\u0000");
        result = COLLATE_NOCASE.matcher(result).replaceAll("");
        result = WITHOUT_ROWID.matcher(result).replaceAll("");
        result = AUTOINCREMENT.matcher(result).replaceAll("");
        result = INTEGER.matcher(result).replaceAll("BIGINT");
        result = FLOATING.matcher(result).replaceAll("DOUBLE PRECISION");
        result = BLOB.matcher(result).replaceAll("BYTEA");
        // The placeholder keeps "INTEGER" inside the identity clause from being rewritten again above.
        return result.replace("\u0000", IDENTITY);
    }

    private static String replaceAll(Pattern pattern, String text, String with) {
        Matcher matcher = pattern.matcher(text);
        return matcher.replaceAll(Matcher.quoteReplacement(with));
    }

    /** The next ' or " at or after {@code from}, or the end of the text. */
    private static int nextQuote(String text, int from) {
        for (int at = from; at < text.length(); at++) {
            char c = text.charAt(at);
            if (c == '\'' || c == '"') {
                return at;
            }
        }
        return text.length();
    }

    /** Just past the quote that closes the one at {@code open}; a doubled quote is part of the text. */
    private static int closingQuote(String text, int open) {
        char quote = text.charAt(open);
        int at = open + 1;
        while (at < text.length()) {
            if (text.charAt(at) == quote) {
                if (at + 1 < text.length() && text.charAt(at + 1) == quote) {
                    at += 2;
                    continue;
                }
                return at + 1;
            }
            at++;
        }
        return text.length();
    }

    /** The statements of a step, each with its trailing ';' and whitespace, so joining them gives the step back. */
    private static java.util.List<String> splitStatements(String sql) {
        java.util.List<String> statements = new java.util.ArrayList<>();
        int start = 0;
        int at = 0;
        while (at < sql.length()) {
            char c = sql.charAt(at);
            if (c == '\'' || c == '"') {
                at = closingQuote(sql, at);
                continue;
            }
            if (c == ';') {
                int end = at + 1;
                while (end < sql.length() && Character.isWhitespace(sql.charAt(end))) {
                    end++;
                }
                statements.add(sql.substring(start, end));
                start = end;
                at = end;
                continue;
            }
            at++;
        }
        if (start < sql.length()) {
            statements.add(sql.substring(start));
        }
        return statements;
    }
}
