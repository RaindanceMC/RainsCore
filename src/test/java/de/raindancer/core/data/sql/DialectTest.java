package de.raindancer.core.data.sql;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Nested;
import org.junit.jupiter.api.Test;

import static org.assertj.core.api.Assertions.assertThat;

class DialectTest {

    @Nested
    @DisplayName("SQLite")
    class Sqlite {

        @Test
        @DisplayName("is left exactly as written — every schema in the field was written for it")
        void untouched() {
            String step = "CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, x REAL, b BLOB COLLATE NOCASE)";
            assertThat(Dialect.SQLITE.translate(step)).isEqualTo(step);
        }
    }

    @Nested
    @DisplayName("PostgreSQL")
    class Postgres {

        private String pg(String sql) {
            return Dialect.POSTGRESQL.translate(sql);
        }

        @Test
        @DisplayName("an INTEGER is 64 bits, as in SQLite — epoch millis do not fit in Postgres' 32-bit integer")
        void integerIsBigint() {
            assertThat(pg("CREATE TABLE t (at INTEGER NOT NULL, n INT)"))
                    .isEqualTo("CREATE TABLE t (at BIGINT NOT NULL, n BIGINT)");
        }

        @Test
        @DisplayName("INTEGER PRIMARY KEY hands out ids by itself, as SQLite's rowid alias does")
        void rowidAlias() {
            assertThat(pg("CREATE TABLE t (id INTEGER PRIMARY KEY, x TEXT)"))
                    .isEqualTo("CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, x TEXT)");
        }

        @Test
        @DisplayName("AUTOINCREMENT goes the same way")
        void autoincrement() {
            assertThat(pg("CREATE TABLE t (id   integer   primary key   autoincrement, x TEXT)"))
                    .isEqualTo("CREATE TABLE t (id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, x TEXT)");
        }

        @Test
        @DisplayName("a composite key is not an identity")
        void compositeKey() {
            assertThat(pg("CREATE TABLE t (a INTEGER NOT NULL, b TEXT, PRIMARY KEY (a, b))"))
                    .isEqualTo("CREATE TABLE t (a BIGINT NOT NULL, b TEXT, PRIMARY KEY (a, b))");
        }

        @Test
        @DisplayName("REAL, DOUBLE and FLOAT are double precision, BLOB is bytea")
        void otherTypes() {
            assertThat(pg("CREATE TABLE t (x REAL, y DOUBLE, z FLOAT, data BLOB NOT NULL)"))
                    .isEqualTo("CREATE TABLE t (x DOUBLE PRECISION, y DOUBLE PRECISION, z DOUBLE PRECISION, data BYTEA NOT NULL)");
        }

        @Test
        @DisplayName("COLLATE NOCASE and WITHOUT ROWID have no meaning there and are dropped")
        void sqliteOnlyClauses() {
            assertThat(pg("CREATE TABLE t (name TEXT COLLATE NOCASE) WITHOUT ROWID"))
                    .isEqualTo("CREATE TABLE t (name TEXT)");
            assertThat(pg("CREATE INDEX i ON t (name COLLATE NOCASE, at DESC)"))
                    .isEqualTo("CREATE INDEX i ON t (name, at DESC)");
        }

        @Test
        @DisplayName("words inside quotes are text, not types")
        void literalsUntouched() {
            assertThat(pg("CREATE TABLE t (kind TEXT NOT NULL DEFAULT 'INTEGER REAL BLOB', n INTEGER)"))
                    .isEqualTo("CREATE TABLE t (kind TEXT NOT NULL DEFAULT 'INTEGER REAL BLOB', n BIGINT)");
            assertThat(pg("CREATE TABLE t (note TEXT DEFAULT 'it''s an INTEGER', n REAL)"))
                    .isEqualTo("CREATE TABLE t (note TEXT DEFAULT 'it''s an INTEGER', n DOUBLE PRECISION)");
        }

        @Test
        @DisplayName("column names that merely contain a type word stay as they are")
        void identifiersUntouched() {
            assertThat(pg("CREATE TABLE t (integer_count INTEGER, realm TEXT, blobs TEXT, \"REAL\" TEXT)"))
                    .isEqualTo("CREATE TABLE t (integer_count BIGINT, realm TEXT, blobs TEXT, \"REAL\" TEXT)");
        }

        @Test
        @DisplayName("ALTER TABLE ... ADD COLUMN gets the same types")
        void alterTable() {
            assertThat(pg("ALTER TABLE t ADD COLUMN ranked INTEGER NOT NULL DEFAULT 1"))
                    .isEqualTo("ALTER TABLE t ADD COLUMN ranked BIGINT NOT NULL DEFAULT 1");
        }

        @Test
        @DisplayName("statements that are not DDL are left alone")
        void dmlUntouched() {
            String dml = "INSERT INTO t (id, kind) VALUES (?, 'REAL') ON CONFLICT(id) DO UPDATE SET kind = excluded.kind";
            assertThat(pg(dml)).isEqualTo(dml);
            assertThat(pg("UPDATE t SET n = 1 WHERE kind = 'INTEGER'")).isEqualTo("UPDATE t SET n = 1 WHERE kind = 'INTEGER'");
        }

        @Test
        @DisplayName("several statements in one step are each translated")
        void severalStatements() {
            assertThat(pg("CREATE TABLE a (n INTEGER); CREATE INDEX a_n ON a (n)"))
                    .isEqualTo("CREATE TABLE a (n BIGINT); CREATE INDEX a_n ON a (n)");
        }

        @Test
        @DisplayName("Core's own schema translates without a single SQLite-only word left in it")
        void coreSchemaIsClean() {
            for (Schema schema : new Schema[]{CoreSchema.CORE, CoreSchema.AUDIT}) {
                for (String step : schema.steps()) {
                    assertThat(pg(step).toUpperCase())
                            .doesNotContainPattern("\\bINTEGER\\b|\\bREAL\\b|\\bBLOB\\b|NOCASE|AUTOINCREMENT|WITHOUT ROWID");
                }
            }
        }
    }

    @Test
    @DisplayName("null and blank are returned as they came")
    void nullAndBlank() {
        assertThat(Dialect.POSTGRESQL.translate(null)).isNull();
        assertThat(Dialect.POSTGRESQL.translate("  ")).isEqualTo("  ");
    }

    @Test
    @DisplayName("a case-insensitive LIKE is ILIKE on Postgres and LIKE on SQLite")
    void caseInsensitiveLike() {
        assertThat(Dialect.SQLITE.likeIgnoringCase()).isEqualTo("LIKE");
        assertThat(Dialect.POSTGRESQL.likeIgnoringCase()).isEqualTo("ILIKE");
    }
}
